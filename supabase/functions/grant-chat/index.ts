// Answers questions about the grant data for the app's Ask tab.
//
// Retrieval: the model can only look things up through the read-only tools
// below, which query the statewide SC data the app shows (sc_grants_public,
// sc_aggregate, and sc_grant_search for exact search totals). Dollar totals
// are computed in the database, never by the model, and the answer must come
// from those results.
//
// Request:  POST {"messages": [{"role": "user" | "assistant", "content": "..."}],
//                 "county": "York County"}   (optional: the app's county filter)
//           header x-device-id: random id generated by the app
// Response: {"answer": "...", "grants": [<sc_grants_public rows used>]}
// Errors:   {"error": "not_configured" | "billing" | "rate_limited" |
//            "bad_request" | "failed"} with a matching HTTP status
//
// Secrets (Supabase → Edge Functions → Secrets, or `supabase secrets set`):
//   OPENAI_API_KEY      required — key from https://platform.openai.com
//   OPENAI_MODEL        optional — defaults to gpt-6-luna (cheapest current
//                       model with tool calling)
//   CHAT_DEVICE_LIMIT   optional — questions per device per day (default 30)
//   CHAT_IP_LIMIT       optional — questions per IP address per day (default 60)
//   CHAT_DAILY_LIMIT    optional — questions per day for everyone (default 2000)
// SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are provided automatically.

import { createClient } from 'npm:@supabase/supabase-js@2'

const MODEL = Deno.env.get('OPENAI_MODEL') ?? 'gpt-6-luna'
const limit = (name: string, fallback: number) => Number(Deno.env.get(name)) || fallback
const DEVICE_LIMIT = limit('CHAT_DEVICE_LIMIT', 30)
const IP_LIMIT = limit('CHAT_IP_LIMIT', 60)
const DAILY_LIMIT = limit('CHAT_DAILY_LIMIT', 2000)

const MAX_TURNS = 8
const MAX_CHARS = 1000
const MAX_TOOL_ROUNDS = 4
const MAX_SOURCES = 8

const db = createClient(Deno.env.get('SUPABASE_URL')!, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!, {
  auth: { persistSession: false },
})

const INSTRUCTIONS = `You are BridgeGrant's assistant. You answer questions about grants
reported in IRS Form 990 and 990-PF filings to recipients in South Carolina
(all 46 counties), tax years 2020-2025.

Rules:
- Use the tools for every fact about funders, recipients, places, years or dollars.
  Answer only from tool results. Never estimate or invent numbers, names, or dates.
- Quote dollar totals and counts exactly as the tools return them.
- If the tools return nothing relevant, say the data doesn't show it and suggest a
  different search. Don't fill gaps from general knowledge.
- The data shows past grants only. It does not show deadlines, eligibility or how
  to apply; say so if asked, and suggest the funder's website or the Help tab.
- Records come from IRS e-file data (NCCS). Describe them as reported IRS
  records; don't call them verified or confirmed.
- Tax years 2024 and 2025 are incomplete (late returns are still arriving), so
  don't describe lower totals in those years as declines.
- Counties come from ZIP codes. Grants whose ZIP crosses county lines or is a PO
  box have no county, so county totals undercount; say so when giving them.
- Results include donor-advised fund sponsors (e.g. Fidelity Charitable) and
  AmazonSmile, which don't take applications; grant_type and funder_type say so.
- Be brief: a short answer, then up to five bullet points. Plain text, no tables.`

const TOOLS = [
  {
    type: 'function',
    name: 'search_grants',
    description:
      'Find individual grant records. Returns the match count, exact total dollars, and the largest matching grants. ' +
      'Use for questions about a specific funder, recipient, city, purpose or year.',
    parameters: {
      type: 'object',
      properties: {
        text: {
          type: 'string',
          description: 'One to four short keywords; a grant matches if any keyword is in its funder, recipient or purpose',
        },
        funder: { type: 'string', description: 'Part of a funder name' },
        recipient: { type: 'string', description: 'Part of a recipient name' },
        city: { type: 'string', description: 'City, e.g. Rock Hill' },
        county: { type: 'string', description: 'County, e.g. York County' },
        tax_year: { type: 'integer' },
        min_amount: { type: 'number' },
        max_amount: { type: 'number' },
      },
      additionalProperties: false,
    },
  },
  {
    type: 'function',
    name: 'rank',
    description:
      'Rank funders, recipients, cities or counties across all tax years by total dollars or number of grants, ' +
      'statewide or within one county.',
    parameters: {
      type: 'object',
      properties: {
        kind: { type: 'string', enum: ['funder', 'recipient', 'city', 'county'] },
        county: { type: 'string', description: 'Limit to one county, e.g. York County; omit for statewide' },
        by: { type: 'string', enum: ['amount', 'count'] },
        name: { type: 'string', description: 'Optional part of a name to filter by' },
        limit: { type: 'integer', description: '1 to 15, default 10' },
      },
      required: ['kind'],
      additionalProperties: false,
    },
  },
  {
    type: 'function',
    name: 'totals',
    description:
      'Overall totals (grants, dollars, median, funders, recipients) for each tax year and for all years, ' +
      'statewide or within one county.',
    parameters: {
      type: 'object',
      properties: { county: { type: 'string', description: 'e.g. York County; omit for statewide' } },
      additionalProperties: false,
    },
  },
]

type Row = Record<string, unknown>

const STOP_WORDS = new Set(['and', 'the', 'for', 'who', 'what', 'with', 'from', 'that', 'grants', 'grant', 'funds', 'fund'])

/** Keeps search text to letters, digits and simple punctuation. */
const clean = (v: unknown) =>
  typeof v === 'string' ? v.replace(/[^\p{L}\p{N}\s&'.-]/gu, ' ').replace(/\s+/g, ' ').trim().slice(0, 80) : ''

/** "york" or "York county" -> "York County"; empty when not given. */
const countyName = (v: unknown) => {
  const c = clean(v).replace(/\s+county$/i, '')
  return c ? c.replace(/\b\w/g, (ch) => ch.toUpperCase()) + ' County' : ''
}

async function searchGrants(args: Row, sources: Map<string, Row>) {
  // Any keyword may match funder, recipient or purpose.
  const words = clean(args.text)
    .toLowerCase()
    .split(' ')
    .filter((w) => w.length > 2 && !STOP_WORDS.has(w))
    .slice(0, 6)
  // Models often fill unused fields with 0 or "", so only real values filter.
  const year = Number(args.tax_year)
  const { data, error } = await db.rpc('sc_grant_search', {
    p_words: words.length ? words : null,
    p_funder: clean(args.funder) || null,
    p_recipient: clean(args.recipient) || null,
    p_city: clean(args.city) || null,
    p_county: countyName(args.county) || null,
    p_tax_year: Number.isInteger(year) && year >= 1990 ? year : null,
    p_min: Number(args.min_amount) > 0 ? Number(args.min_amount) : null,
    p_max: Number(args.max_amount) > 0 ? Number(args.max_amount) : null,
  })
  if (error) throw new Error(error.message)
  const result = data as Row
  const top = (result.largest as Row[]) ?? []
  for (const r of top.slice(0, 4)) if (sources.size < MAX_SOURCES) sources.set(String(r.id), r)
  return {
    match_count: result.match_count,
    total_usd: result.total_usd,
    funders: result.funders,
    recipients: result.recipients,
    largest: top.map((r) => ({
      funder: r.funder,
      recipient: r.recipient,
      amount_usd: r.amount_usd,
      tax_year: r.tax_year,
      city: r.city,
      county: r.county,
      purpose: r.purpose,
      grant_type: r.grant_type,
      funder_type: r.funder_type,
    })),
  }
}

async function rank(args: Row) {
  const kind = ['funder', 'recipient', 'city', 'county'].includes(String(args.kind)) ? String(args.kind) : 'funder'
  const by = args.by === 'count' ? 'grant_count' : 'total_amount_usd'
  const n = Math.min(Math.max(Number(args.limit) || 10, 1), 15)
  const county = countyName(args.county) || null
  let q = db.rpc('sc_aggregate', { p_group: kind, p_county: county }).select('label,grant_count,total_amount_usd')
  if (clean(args.name)) q = q.ilike('label', `%${clean(args.name)}%`)
  const { data, error } = await q.order(by, { ascending: false }).limit(n)
  if (error) throw new Error(error.message)
  return { kind, county: county ?? 'statewide', ranked_by: by, rows: data }
}

async function totals(args: Row) {
  const county = countyName(args.county) || null
  const [years, all] = await Promise.all([
    db.rpc('sc_aggregate', { p_group: 'tax_year', p_county: county }).order('label'),
    db.rpc('sc_aggregate', { p_group: 'overview', p_county: county }).maybeSingle(),
  ])
  if (years.error) throw new Error(years.error.message)
  return { county: county ?? 'statewide', by_tax_year: years.data, all_years: all.data, partial_years: [2024, 2025] }
}

async function runTool(name: string, rawArgs: string, sources: Map<string, Row>) {
  let args: Row = {}
  try {
    args = JSON.parse(rawArgs || '{}')
  } catch {
    return { error: 'Arguments were not valid JSON.' }
  }
  try {
    if (name === 'search_grants') return await searchGrants(args, sources)
    if (name === 'rank') return await rank(args)
    if (name === 'totals') return await totals(args)
    return { error: `Unknown tool ${name}` }
  } catch (e) {
    console.error('tool failed', name, e)
    return { error: 'The lookup failed.' }
  }
}

class ChatError extends Error {
  constructor(readonly code: string, readonly status: number) {
    super(code)
  }
}

async function openai(body: Row) {
  const key = Deno.env.get('OPENAI_API_KEY')
  if (!key) throw new ChatError('not_configured', 503)
  const res = await fetch('https://api.openai.com/v1/responses', {
    method: 'POST',
    headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  })
  const json = await res.json().catch(() => ({}))
  if (!res.ok) {
    const code = json?.error?.code ?? json?.error?.type
    console.error('openai error', res.status, code, json?.error?.message)
    if (code === 'insufficient_quota' || res.status === 402) throw new ChatError('billing', 402)
    if (res.status === 401) throw new ChatError('not_configured', 503)
    throw new ChatError('failed', 502)
  }
  return json
}

const outputText = (response: Row) =>
  ((response.output as Row[]) ?? [])
    .filter((o) => o.type === 'message')
    .flatMap((o) => (o.content as Row[]) ?? [])
    .filter((c) => c.type === 'output_text')
    .map((c) => c.text)
    .join('')
    .trim()

async function answer(messages: { role: string; content: string }[], county: string, trace?: Row[]) {
  const sources = new Map<string, Row>()
  const base = {
    model: MODEL,
    instructions: county
      ? `${INSTRUCTIONS}\n\nThe user has the app set to ${county}. Pass county "${county}" to the tools ` +
        `unless they ask about another place or all of South Carolina.`
      : INSTRUCTIONS,
    tools: TOOLS,
    reasoning: { effort: 'low' },
    max_output_tokens: 1500,
  }
  let response = await openai({ ...base, input: messages })
  for (let round = 0; round < MAX_TOOL_ROUNDS; round++) {
    const calls = ((response.output as Row[]) ?? []).filter((o) => o.type === 'function_call')
    if (calls.length === 0) break
    const outputs = await Promise.all(
      calls.map(async (c) => {
        const result = await runTool(String(c.name), String(c.arguments ?? ''), sources)
        trace?.push({ tool: c.name, args: c.arguments, result })
        return { type: 'function_call_output', call_id: c.call_id, output: JSON.stringify(result) }
      }),
    )
    response = await openai({ ...base, previous_response_id: response.id, input: outputs })
  }
  // The app shows plain text, so drop Markdown bold/italic markers.
  const text = outputText(response).replace(/\*\*(.+?)\*\*/g, '$1').replace(/__(.+?)__/g, '$1')
  return {
    answer: text || "Sorry, I couldn't find an answer in the grant data. Try rephrasing your question.",
    grants: [...sources.values()],
  }
}

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } })

Deno.serve(async (req) => {
  if (req.method !== 'POST') return json({ error: 'bad_request' }, 405)

  const body = await req.json().catch(() => null)
  const raw = Array.isArray(body?.messages) ? body.messages : []
  const messages = raw
    .filter((m: Row) => (m?.role === 'user' || m?.role === 'assistant') && typeof m?.content === 'string')
    .slice(-MAX_TURNS)
    .map((m: Row) => ({ role: String(m.role), content: String(m.content).slice(0, MAX_CHARS) }))
  if (messages.length === 0 || messages[messages.length - 1].role !== 'user') {
    return json({ error: 'bad_request' }, 400)
  }

  const device = clean(req.headers.get('x-device-id')).slice(0, 64) || 'unknown'
  const ip = (req.headers.get('x-forwarded-for') ?? '').split(',')[0].trim() || 'unknown'
  const { data: allowed, error: quotaError } = await db.rpc('consume_chat_quota', {
    p_keys: [`device:${device}`, `ip:${ip}`, 'all'],
    p_limits: [DEVICE_LIMIT, IP_LIMIT, DAILY_LIMIT],
  })
  if (quotaError) {
    console.error('quota check failed', quotaError.message)
    return json({ error: 'failed' }, 500)
  }
  if (!allowed) return json({ error: 'rate_limited' }, 429)

  try {
    // x-debug: 1 adds the tool calls and their results, for checking answers.
    const trace = req.headers.get('x-debug') === '1' ? [] : undefined
    const county = countyName(body?.county)
    const result = await answer(messages, county, trace)
    return json(trace ? { ...result, trace } : result)
  } catch (e) {
    if (e instanceof ChatError) return json({ error: e.code }, e.status)
    console.error('chat failed', e)
    return json({ error: 'failed' }, 500)
  }
})
