def columns_of(conn: sqlite3.Connection, table: str) -> list[str]:
    return [r[1] for r in conn.execute(f"PRAGMA table_info({table})")]


def insert(conn: sqlite3.Connection, table: str, df: pd.DataFrame) -> None:
    cols = [c for c in columns_of(conn, table) if c in df.columns]
    data = df[cols].astype(object).where(df[cols].notna(), None)
    for c in cols:
        if df[c].dtype == bool:
            data[c] = df[c].astype(int)
    conn.executemany(
        f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})",
        data.itertuples(index=False, name=None),
    )


def main() -> int:
    df = pd.read_parquet(stage_path("verified.parquet"))
    evidence = pd.read_parquet(stage_path("verification_evidence.parquet"))
    for c in ("is_amended_return", "is_mostly_noncash", "source_table_match", "irs_filing_verified",
              "recipient_identity_verified", "sc_address_verified", "county_verified", "recipient_exemption_revoked"):
        df[c] = df[c].fillna(False).astype(bool)

    funders = funders_table(df)
    funders["id"] = range(1, len(funders) + 1)
    funders["likely_open_to_applicants"] = funders["likely_open_to_applicants"].astype(bool)

    df["recipient_key"] = recipient_key(df)
    rec = (
        df.sort_values("tax_year")
        .groupby("recipient_key", as_index=False)
        .agg(
            recipient_ein=("recipient_ein", "last"),
            recipient_name=("recipient_name", "last"),
            recipient_name_clean=("recipient_name_clean", "last"),
            recipient_type=("recipient_type", "last"),
            recipient_city=("recipient_city", "last"),
            recipient_zip=("recipient_zip", "last"),
            recipient_county=("recipient_county", "last"),
            county_status=("county_status", "last"),
            recipient_identity_verified=("recipient_identity_verified", "max"),
            recipient_exemption_revoked=("recipient_exemption_revoked", "max"),
        )
    )
    rec["id"] = range(1, len(rec) + 1)

    fid = dict(zip(funders["funder_ein"], funders["id"]))
    grants = df.copy()
    grants["funder_id"] = grants["funder_ein"].map(fid)
    if grants["funder_id"].isna().any():  # funders without an EIN
        by_name = dict(zip(funders["funder_name"], funders["id"]))
        grants["funder_id"] = grants["funder_id"].fillna(grants["funder_name"].map(by_name))
    grants["recipient_id"] = grants["recipient_key"].map(dict(zip(rec["recipient_key"], rec["id"])))
    grants["tax_year"] = grants["tax_year"].astype(int)
    grants["id"] = range(1, len(grants) + 1)

    evidence = evidence.merge(grants[["record_id", "id"]].rename(columns={"id": "grant_id"}), on="record_id", how="inner")
    evidence["id"] = range(1, len(evidence) + 1)

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    DB_PATH.unlink(missing_ok=True)
    with sqlite3.connect(DB_PATH) as conn:
        conn.executescript(SCHEMA)
        insert(conn, "funders", funders)
        insert(conn, "recipients", rec)
        insert(conn, "grants", grants)
        insert(conn, "verification_evidence", evidence)
        conn.commit()
        counts = {t: conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
                  for t in ("funders", "recipients", "grants", "verification_evidence")}

    PRISMA_PATH.parent.mkdir(parents=True, exist_ok=True)
    PRISMA_PATH.write_text(PRISMA)
    print(f"  {DB_PATH.relative_to(ROOT)}: " + ", ".join(f"{t} {n:,}" for t, n in counts.items()))
    print(f"  {PRISMA_PATH.relative_to(ROOT)} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
